//! Intel graphics generation dispatch, shared by driver policy and backends.
//! PCI IDs cross-checked against Linux v6.6 include/drm/i915_pciids.h.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Generation {
    Skylake,
    KabyLake,
    CoffeeLake,
}

pub fn generation(vendor: u16, device: u16, class: u32) -> Option<Generation> {
    if vendor != 0x8086 || !matches!(class >> 8, 0x0300 | 0x0302 | 0x0380) {
        return None;
    }
    match device {
        0x1906 | 0x1913 | 0x190e | 0x1915 | 0x1902 | 0x190a | 0x190b | 0x1917 | 0x1916 | 0x1921
        | 0x191e | 0x1912 | 0x191a | 0x191b | 0x191d | 0x1923 | 0x1926 | 0x1927 | 0x192a
        | 0x192b | 0x192d | 0x1932 | 0x193a | 0x193b | 0x193d => Some(Generation::Skylake),
        0x5906 | 0x5913 | 0x590e | 0x5915 | 0x5902 | 0x5908 | 0x590a | 0x590b | 0x5916 | 0x5921
        | 0x591e | 0x5912 | 0x5917 | 0x591a | 0x591b | 0x591d | 0x5926 | 0x5923 | 0x5927
        | 0x593b => Some(Generation::KabyLake),
        0x3e90 | 0x3e93 | 0x3e99 | 0x3e91 | 0x3e92 | 0x3e96 | 0x3e98 | 0x3e9a | 0x3e9c | 0x3e94
        | 0x3e9b | 0x3ea9 | 0x3ea5 | 0x3ea6 | 0x3ea7 | 0x3ea8 => Some(Generation::CoffeeLake),
        _ => None,
    }
}
