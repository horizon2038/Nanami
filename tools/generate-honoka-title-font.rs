//! Regenerate from the repository root using fontdue 0.9.3, linked from the
//! native-performance release dependencies. Print to stdout for review.
use fontdue::{Font, FontSettings};
fn main() {
    let bytes = std::fs::read("nanami/servers/apps/honoka/assets/fonts/hack.ttf").unwrap();
    let font = Font::from_bytes(bytes, FontSettings {
        scale: 13.0, load_substitutions: false, ..FontSettings::default()
    }).unwrap();
    println!("// Generated by tools/generate-honoka-title-font.rs; do not edit by hand.");
    println!("// Hack font: MIT, Copyright (c) 2018 Source Foundry Authors.");
    println!("// hack.ttf SHA256: 41366767b9fd99c5bd1ef8197f97c000786acd2faf0ad7f089925facbed397d4");
    println!("// fontdue 0.9.3, size/scale 13.0, substitutions disabled.");
    println!("static TITLE_GLYPHS: [CachedGlyph; COUNT] = [");
    for ch in 32u8..128 {
        let (m, pixels) = font.rasterize(ch as char, 13.0);
        let width = m.width.min(24);
        let height = m.height.min(24);
        let integer = m.advance_width as i32;
        let advance = (integer + i32::from(m.advance_width > integer as f32)).max(1);
        println!("    CachedGlyph {{ cached: true, width: {width}, height: {height}, advance: {advance}, x_offset: {}, y_offset: {}, bitmap: title_bitmap(&[", m.xmin, 10 - m.ymin - height as i32);
        for y in 0..height {
            print!("        ");
            for x in 0..width {
                let value = pixels[y * m.width + x];
                print!("{value},");
            }
            println!();
        }
        println!("    ], {width}, {height}) }},");
    }
    println!("];");
}
